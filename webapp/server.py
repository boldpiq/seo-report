#!/usr/bin/env python3
"""
Boldpiq Website Audit — web front end.

A small HTTP service that wraps seo_report.py so staff can generate a client
visibility report from a browser instead of a terminal. Standard library only,
matching the rest of the tool.

Design notes worth keeping:

- ONE WORKER, ON PURPOSE. Jobs run strictly one at a time. seoscore.tools' terms
  forbid excessive scanning, and a headless Chrome run is the heaviest thing on
  the box. Serialising also means a queue of three is 2 minutes, not three
  simultaneous Chrome instances fighting for RAM.
- NO AUTHENTICATION HERE. This sits behind Cloudflare Access, the same as n8n.
  Do not expose the port directly to the internet — there is nothing stopping
  anyone from queueing scans.
- The report is generated by shelling out to the CLI rather than importing it,
  so a crash in one scan can never take the server down, and the CLI stays the
  single source of truth for how a report is built.
"""

