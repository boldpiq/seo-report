def profile(detected_cms):
    """Return the platform profile for a detected CMS key."""
    key = (detected_cms or "").strip().lower()
    return PLATFORMS.get(key, PLATFORMS["_generic"]), key in PLATFORMS


def constraint(prof, check_id):
    """(status, reason) for a check on this platform, or None."""
    return prof.get("constraints", {}).get(check_id)
