"""
Platform and architecture constraints.

Some findings simply cannot be fixed on the platform the site is built on. A
closed builder like Wix will not let anyone set a security header no matter how
much they pay, and telling a client to "add a Content-Security-Policy" on Wix is
advice they can never act on.

This module says so plainly: per platform, which checks are hard-blocked, which
are constrained, and what the realistic alternative is.

    BLOCKED  — not fixable on this stack. The only real fix is replatforming.
    LIMITED  — fixable, but constrained by the platform or costly to do properly.

Written conservatively: platforms change, so the wording says "typically" and the
report frames these as things to confirm rather than absolutes.
"""

BLOCKED, LIMITED = "blocked", "limited"

